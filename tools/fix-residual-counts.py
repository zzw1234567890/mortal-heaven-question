def apply(path, pairs):
    t = io.open(path, encoding="utf-8").read()
    total = 0
    for a, b in pairs:
        c = t.count(a)
        if c:
            t = t.replace(a, b)
        total += c
        print("  %dx  %s" % (c, a[:32]))
    io.open(path, "w", encoding="utf-8").write(t)
    print("  => %d replacements" % total)


